# Número total de tickets que queremos generar.
NUM_TICKETS = 200_000

# Definimos el periodo temporal en el que se generarán las ventas.
START_DATE = pd.Timestamp("2024-01-01")
END_DATE = pd.Timestamp("2025-12-31 23:59:59")


# Obtenemos únicamente los IDs de las tiendas físicas.
# Esta lista se utilizará posteriormente para asignar una tienda
# a los tickets generados en canal físico.
physical_stores = stores_df[
    stores_df["store_type"] == "PHYSICAL"
]["store_id"].tolist()


