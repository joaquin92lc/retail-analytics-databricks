# ============================================================
# GENERACIÓN DE TICKETS DE VENTA
# ============================================================

# Lista donde almacenaremos cada ticket generado.
tickets = []

for i in range(1, NUM_TICKETS + 1):

    # Generamos un identificador único para cada ticket.
    sale_id = f"T{i:07d}"

    # Generamos una fecha y hora aleatoria dentro del
    # periodo histórico definido anteriormente.
    total_seconds = int(
        (END_DATE - START_DATE).total_seconds()
    )

    random_seconds = random.randint(0, total_seconds)

    sale_timestamp = START_DATE + pd.Timedelta(
        seconds=random_seconds
    )

    # Aproximadamente el 10% de las ventas serán ONLINE
    # y el 90% se realizarán en tiendas físicas.
    if random.random() < 0.10:
        sales_channel = "ONLINE"
        store_id = "S999"

        # Métodos de pago disponibles para compras online.
        payment_method = random.choices(
            ["CARD", "PAYPAL", "TRANSFER"],
            weights=[0.65, 0.25, 0.10],
            k=1
        )[0]

    else:
        sales_channel = "PHYSICAL"

        # Seleccionamos aleatoriamente una tienda física.
        store_id = random.choice(physical_stores)

        # Métodos de pago disponibles en tienda física.
        payment_method = random.choices(
            ["CARD", "CASH"],
            weights=[0.80, 0.20],
            k=1
        )[0]

    # Aproximadamente el 15% de las compras serán anónimas,
    # por lo que no estarán asociadas a ningún cliente.
    if random.random() < 0.15:
        customer_id = None

    else:
        # Solo permitimos asociar clientes cuya fecha de registro
        # sea anterior o igual a la fecha de la compra.
        valid_customers = customers_df[
            customers_df["registration_date"]
            <= sale_timestamp
        ]["customer_id"]

        customer_id = (
            random.choice(valid_customers.tolist())
            if len(valid_customers) > 0
            else None
        )

    # Añadimos el ticket generado a la lista.
    tickets.append(
        {
            "sale_id": sale_id,
            "sale_timestamp": sale_timestamp,
            "store_id": store_id,
            "customer_id": customer_id,
            "sales_channel": sales_channel,
            "payment_method": payment_method
        }
    )


